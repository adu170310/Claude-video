GLYPHS = {k: np.array([[c == "#" for c in row] for row in v], dtype=np.uint8) for k, v in _G.items()}

def cells(s):
    """Low-res bitmap (7 rows) for a string; 1 blank column between glyphs."""
    cols = []
    for i, ch in enumerate(s):
        g = GLYPHS[ch if ch in GLYPHS else ch.upper()]
        if i:
            cols.append(np.zeros((7, 1), np.uint8))
        cols.append(g)
    return np.hstack(cols) if cols else np.zeros((7, 0), np.uint8)

def width(s, scale):
    return (6 * len(s) - 1) * scale
